// require Xcode compilation and physical AirPods/iOS validation.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(path, 'utf8');
const root = 'apps/mobile/modules/sda-core/ios/';
const tracking = read(root + 'HeadphoneTracking.swift');
const player = read(root + 'SdaPlayer.swift');
const module = read(root + 'SdaModule.swift');
assert.match(tracking, /self.motionSession == session, self.allowsHeadTrackingNow/);
assert.match(tracking, /audio\?\.isRunning == true/);
assert.match(tracking, /!isPaused && !done && !sessionInterrupted/);
assert.match(tracking, /motionBackgroundCallbackCount \+= 1/);
assert.match(tracking, /motion.timestamp >= self.motionReferenceAfter/);
assert.match(tracking, /motionReferenceAfter = ProcessInfo.processInfo.systemUptime/);
assert.match(tracking, /func applyNeutralHeadPose/);
assert.doesNotMatch(tracking, /motionReference!|motionAcceptedPose|acos\(/);
assert.doesNotMatch(tracking, /motionRawPose/);
assert.match(tracking, /self.command\("trackingProvider"/);
const native = read('crates/sda-native/src/lib.rs');
assert.match(native, /apps\/head-tracking-helper\/src\/orientation.rs/);
assert.match(read('crates/sda-native/src/ios.rs'), /\.process_quaternion/);
const app = read('apps/mobile/App.tsx');
assert.doesNotMatch(app, /HeadTrackingSession|trackingTimer|headTrackingRawPose|setTrackedHeadPose/);
assert.doesNotMatch(module, /headTrackingRawPose|setTrackedHeadPose/);
assert.match(read('crates/sda-native/src/ios.rs'), /if tracking_pose_changed\(\*last, orientation\)/);
assert.match(read('crates/sda-native/src/ios.rs'), /e.set_head_orientation\(orientation\)/);
assert.match(tracking, /handle != nil && !motionNeutralApplied/);
assert.match(tracking, /systemUptime - self.motionLastSample > 1/);
assert.match(tracking, /if motionWatchdog != nil \{ headphoneMotion.stopDeviceMotionUpdates\(\) \}/);
assert.match(player, /lazy var headphoneMotion = CMHeadphoneMotionManager\(\)/);
assert.match(tracking, /motionWatchdog\?\.cancel\(\)/);
assert.match(tracking, /now >= self.motionRetryAfter/);
assert.match(tracking, /self.stopHeadTracking\(\)\s*self.startHeadTracking\(\)/);
assert.match(player, /UIScreen.capturedDidChangeNotification/);
const recovery = player.slice(player.indexOf('func recoverOutputIfNeeded'), player.indexOf('func installSystemControls'));
assert.match(recovery, /startHeadTracking\(\)/);
assert.match(player, /if !self.allowsHeadTrackingNow \{ self.stopHeadTracking\(\) \} else \{ self.startHeadTracking\(\) \}/);
assert.match(player, /func stopNative\(keepMotion: Bool = false\)/);
assert.match(player, /if !keepMotion \{ stopHeadTracking\(\) \}/);
assert.match(player, /handle = h\s*prepareHeadTrackingForPlayback\(\)/);

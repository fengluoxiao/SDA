const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('apps/mobile/src/AndroidSettings.tsx', 'utf8');
const sections = ['播放操作', '播放', '空间渲染', '应用与输出'].map(title => source.indexOf(`section("${title}"`));
assert.ok(sections.every(index => index >= 0));
assert.deepEqual(sections, [...sections].sort((a,b) => a-b));
for (const callback of ['setVolumeBalance', 'setPlaybackMode', 'setRenderingPreset', 'setRendering']) assert.ok(source.includes(`p.${callback}`));
assert.match(source, /p\.busy \|\| !p\.selectedUri/);
assert.match(source, /p\.busy \|\| !p\.playing/);
assert.match(source, /menu\("渲染预设"/);
assert.match(source, /presetDisabled/);
assert.doesNotMatch(source, /p\.setSystemSpatial360RA|p\.setSystemSpatialStereo/);
assert.match(source, /p\.setAlacStereoUpmix/);
assert.match(source, /p\.setSpatialCueDb\(Number\(id\)\)/);
assert.match(source, /p\.setSpatialEnhancement/);
assert.match(source, /onClose\(\); callback\(\)/);
assert.match(source, /<compose.Switch value=\{value\} enabled=\{!disabled\} onCheckedChange=\{onChange\}/);
assert.match(source, /header: \{ height: 64/);
assert.match(source, /accessibilityRole="radio"/);
assert.doesNotMatch(source, /#007aff|#34c759|#f2f2f7/);
console.log('Android settings: section order, actions, menus, disabled states and platform capability boundaries passed.');

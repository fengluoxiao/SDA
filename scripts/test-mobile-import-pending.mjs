import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {transformSync} from 'esbuild';
const source=readFileSync('apps/mobile/App.tsx','utf8').replace(/\r\n/g,'\n');
const choose=source.match(/  private chooseFile = async \(\) => \{[\s\S]*?\n  };/)[0];
const sync=source.match(/  private syncNativeQueue = \(\) => \{[\s\S]*?\n  };/)[0];
const mod={exports:{}};
let releaseHash;
const hashWait=new Promise(resolve=>releaseHash=resolve);
const assets=[{uri:'file://slow',name:'slow.m4a'},{uri:'file://bad',name:'bad.m4a'},{uri:'file://ok',name:'ok.mp3'}];
const DocumentPicker={getDocumentAsync:async()=>({canceled:false,assets})};
new Function('module','exports','DocumentPicker','Platform',transformSync(`export class Harness {${choose}\n${sync}}`,{loader:'ts',format:'cjs'}).code)(mod,mod.exports,DocumentPicker,{OS:'ios'});
const h=new mod.exports.Harness();
h.state={queue:[],queueIndex:-1,busy:false,playbackMode:'sequential'};
h.preparedTracks=new Map();h.changingTrack=false;
h.setState=(update,callback)=>{Object.assign(h.state,typeof update==='function'?update(h.state):update);callback?.();};
const nativeQueues=[];
const engine={contentHash:async uri=>{if(uri==='file://slow')await hashWait;return uri;},metadata:async()=>JSON.stringify({title:'Song'})};
h.engine={configurePlaybackQueue:json=>nativeQueues.push(JSON.parse(json))};h.getEngine=()=>engine;
let sawProgress=false;
h.prepareTrack=async(track,callback)=>{
  if(track.uri==='file://bad')throw Error('test import failure');
  callback?.({fraction:.5,stage:'提取 360 Reality Audio 音轨'});
  const row=h.state.queue.find(row=>row.uri===track.uri);
  assert.equal(row.preparation.state,'loading');assert(row.preparation.progress>.5&&row.preparation.progress<1);sawProgress=true;
};
const task=h.chooseFile();await new Promise(resolve=>setImmediate(resolve));
assert.equal(h.state.queue.length,3,'all picked rows visible before hashing/import completes');
assert(h.state.queue.every(row=>row.preparation.state==='loading'));
assert.equal(h.state.queueIndex,-1);
releaseHash();await task;
assert(sawProgress);
assert.equal(h.state.queue[0].preparation,undefined);
assert.equal(h.state.queue[1].preparation.state,'failed');
assert.equal(h.state.queue[2].preparation,undefined,'failure must not block later files');
assert.equal(h.state.busy,false);assert.equal(h.changingTrack,false);
assert.equal(h.state.queueIndex,0);
assert(nativeQueues.every(queue=>queue.every(track=>track.hash!=='file://bad'&&!track.hash.startsWith('pending:'))));
assert.equal(nativeQueues.at(-1).length,2);
assert.match(source,/!track \|\| track\.preparation/,'loading/failed rows must not play');
const overlay=readFileSync('apps/mobile/src/QueuePreparationOverlay.tsx','utf8');
assert.match(overlay,/left: `\$\{progress \* 100\}%`/);
assert.match(readFileSync('apps/mobile/src/IOSPlayer.tsx','utf8'),/disabled=\{p.busy \|\| !!track.preparation\}/);
console.log('Pending imports: immediate rows, actual progress, partial failure, ready-only native queue, disabled rows passed.');

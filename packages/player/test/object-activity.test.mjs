import assert from "node:assert/strict";
import {ObjectActivityFilter} from "../src/object-activity.ts";
const point=(id,x=0)=>({id,pos:[x,0,0],hasPos:true,size:[0,0,0],gainDb:0,anchor:"room",distanceM:null,distanceInfinite:false});
const quiet=new Set(),fixed=point(1),moving=point(2),filter=new ObjectActivityFilter();
assert.deepEqual(filter.project([fixed,moving],quiet,0),[],"silence never creates an object marker");
assert.deepEqual(filter.project([fixed,point(2,.9)],quiet,.1),[],"movement without sound stays hidden");
const audible=filter.project([fixed,moving],new Set([1]),.2);
assert.deepEqual(audible.map(o=>o.id),[1],"a sounding fixed object appears immediately");
assert.equal(audible[0].sceneOpacity,1,"fixed objects receive full brightness");
assert.equal(fixed.sceneOpacity,undefined,"preserve authoritative metadata");
assert.strictEqual(filter.project([fixed,moving],new Set([1]),.4),audible,"sustained stationary sound does not rebuild its dot");
assert.equal(filter.project([fixed,moving],quiet,.45)[0].sceneOpacity,1,"short signal gaps do not flicker");
const fade=filter.project([fixed,moving],quiet,.6)[0].sceneOpacity;assert(fade>0&&fade<1);
assert.deepEqual(filter.project([fixed,moving],quiet,.8),[],"fade completes even when the playback position is paused");
assert.deepEqual(filter.project([fixed,moving],new Set([1,2]),.9).map(o=>o.id),[1,2],"activity handles moving and fixed sources equally");
assert.deepEqual(filter.project([],new Set([1]),1),[],"removed sources disappear");
assert.deepEqual(filter.project([fixed],quiet,1.1),[],"a redeclared silent source has no stale activity");
assert.deepEqual(filter.project([fixed],new Set([99]),1.2),[],"ignore unknown source activity");
assert.deepEqual(filter.project([{...fixed,hasPos:false}],new Set([1]),1.3),[],"do not invent geometry");
assert.equal(filter.project([fixed],new Set([1]),1.4)[0].sceneOpacity,1,"resuming sound restores full brightness immediately");
assert.deepEqual(filter.project([fixed],quiet,0),[],"animation clock reset clears old trails");
console.log("PASS: fixed/moving signal visibility, silence exclusion, full brightness, hold/fade, pause, resume, removal and inventory integrity");

import assert from 'node:assert/strict';
import { build } from 'esbuild';
const output = await build({ entryPoints: ['packages/player/src/presentation-clock.ts'], bundle: true, format: 'esm', write: false });
const { PresentationClock } = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString('base64')}`);
const clock = new PresentationClock();
assert.equal(clock.read(4800, 0, 48000, true), 4800);
assert.equal(clock.read(4800, 33, 48000, true), 6384);
assert.equal(clock.read(4800, 66, 48000, true), 7968);
assert.equal(clock.read(4800, 1000, 48000, true), 9600, 'stalled native clock must not predict indefinitely');
assert.equal(clock.read(7200, 1010, 48000, true), 9600, 'late report must not rewind the scene');
assert.equal(clock.read(9600, 1020, 48000, false), 9600);
assert.equal(clock.read(9600, 5000, 48000, false), 9600, 'paused display must freeze');
assert.equal(clock.read(9600, 6000, 48000, true), 9600, 'resume must not extrapolate the pause duration');
assert.equal(clock.read(9600, 6050, 48000, true), 12000);
clock.reset();
assert.equal(clock.read(0, 7000, 44100, false), 0, 'replacement stream resets the display clock');
assert.equal(clock.read(4410, 7100, 44100, true), 4410);
assert.equal(clock.read(4410, 7150, 44100, true), 6615);
console.log('presentation clock: cadence, stall, late report, pause/resume and reset passed');
